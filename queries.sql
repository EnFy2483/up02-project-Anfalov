-- Задание 1. Самый дорогой товар
SELECT название, цена
FROM Товар
ORDER BY цена DESC
LIMIT 1;


-- Задание 2. Самый дешёвый товар
SELECT название, цена
FROM Товар
ORDER BY цена ASC
LIMIT 1;


-- Задание 3. Товары одной категории
SELECT название, цена
FROM Товар
WHERE категория = 'Электроника';


-- Задание 4. Поиск по названию
SELECT *
FROM Товар
WHERE название LIKE '%о%';


-- Задание 5. Все заказы
SELECT id, дата, клиент, товар_id, количество
FROM Заказ;


-- Задание 6. Заказы конкретного клиента
SELECT *
FROM Заказ
WHERE клиент = 'Иванов Иван Иванович';


-- Задание 7. JOIN — заказы с названиями товаров
SELECT Заказ.дата, Заказ.клиент, Товар.название, Заказ.количество
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;


-- Задание 8. Общая сумма всех заказов
SELECT SUM(Товар.цена * Заказ.количество) AS итого_сумма
FROM Заказ
JOIN Товар ON Заказ.товар_id = Товар.id;


-- Задание 9. Количество заказов по клиентам
SELECT клиент, COUNT(*) AS количество_заказов
FROM Заказ
GROUP BY клиент;


-- Задание 10. Свой запрос
SELECT название, цена, количество
FROM Товар
WHERE цена > 1000 AND количество > 0
ORDER BY цена DESC;